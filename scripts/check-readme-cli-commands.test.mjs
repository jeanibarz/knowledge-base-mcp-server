import { checkDocs, DOCS_EXCLUDED_DIRS, extractReadmeCommands, findUnknownCommands, findUnknownFlags, isGeneratedDoc, listDocFiles } from './check-readme-cli-commands.mjs';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { test } from 'node:test';
import assert from 'node:assert/strict';

test('extracts commands from code spans and fences only', () => {
  const md = 'Run `kb doctor` now. The kb tool is nice.\n```bash\nkb search "x" --k=5\necho hi | kb remember --stdin\n```\n';
  assert.deepEqual(extractReadmeCommands(md), ['doctor', 'remember', 'search']);
});

test('flags commands missing from the CLI', () => {
  assert.deepEqual(findUnknownCommands('`kb doctor` and `kb bogus`', ['doctor']), ['bogus']);
});

const REGISTRY = [
  { name: 'search', usage: ['kb search <query> --refresh [options]'], options: [{ flags: ['--tag'] }, { flags: ['--kb'] }] },
  { name: 'tags', usage: ['kb tags [--kb=<name>] [--facet=<name>] [--format=md|json]'], options: [] },
];

test('accepts flags from a command\'s options and usage lines', () => {
  const md = '```bash\nkb search q --tag=x --kb=work --refresh\nkb tags --facet=status --format=json\n```\n';
  assert.deepEqual(findUnknownFlags(md, REGISTRY), []);
});

test('flags undocumented flags, including inside a # shell comment (issue #1284)', () => {
  const md = '```bash\nkb tags --facet=status   # vocabulary for kb search --status filters\n```\nAlso `kb search q --type=x`.\n';
  assert.deepEqual(findUnknownFlags(md, REGISTRY), ['kb search --status', 'kb search --type']);
});

test('attributes flags to the nearest preceding command and stops at pipes', () => {
  const md = '```bash\nkb search q --tag=a | grep --color x\nkb tags --tag=a\n```\n';
  assert.deepEqual(findUnknownFlags(md, REGISTRY), ['kb tags --tag']);
});

test('skips commands absent from the registry', () => {
  assert.deepEqual(findUnknownFlags('`kb bogus --whatever`', REGISTRY), []);
});

test('checks flags on backslash-continued lines', () => {
  const md = '```bash\nkb search q \\\n  --status=x \\\n  --tag=y\n```\n';
  assert.deepEqual(findUnknownFlags(md, REGISTRY), ['kb search --status']);
});

test('a trailing `kb` word does not pair with the next line (issue #1287)', () => {
  assert.deepEqual(extractReadmeCommands('```bash\nwhich -a kb\nkb doctor\n```\n'), ['doctor']);
});

test('skips mermaid fences but still scans other fences', () => {
  const md = '```mermaid\nflowchart TB\n  CLI["39-command kb dispatcher"]\n```\n```sh\nkb doctor\n```\n';
  assert.deepEqual(extractReadmeCommands(md), ['doctor']);
});

test('detects the generated-file marker near the top only', () => {
  assert.equal(isGeneratedDoc('# X\n\n<!-- This file is generated by scripts/gen.mjs. Do not edit by hand. -->\n'), true);
  assert.equal(isGeneratedDoc('# Hand-written\n\nkb doctor\n'), false);
});

test('checkDocs reports file: command and file: flag for each doc', () => {
  const docs = [
    { file: 'README.md', markdown: '`kb search q --tag=a`' },
    { file: 'docs/a.md', markdown: '`kb bogus` and `kb tags --tag=x`' },
  ];
  assert.deepEqual(checkDocs(docs, REGISTRY), {
    commands: ['docs/a.md: kb bogus'],
    flags: ['docs/a.md: kb tags --tag'],
  });
});

test('listDocFiles walks docs/ and skips excluded subtrees', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'kb-doc-list-'));
  try {
    for (const f of ['README.md', 'docs/b.md', 'docs/ops/a.md', 'docs/rfcs/001.md', 'docs/testing/fixtures/x.md', 'docs/img.png']) {
      fs.mkdirSync(path.dirname(path.join(root, f)), { recursive: true });
      fs.writeFileSync(path.join(root, f), '');
    }
    assert.deepEqual(listDocFiles(root), ['README.md', 'docs/b.md', 'docs/ops/a.md']);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test('real tree: hand-written docs are scanned, generated and RFC docs are not', () => {
  const files = listDocFiles();
  assert.ok(files.includes('docs/operations/research-workflow.md'));
  assert.ok(!files.some((f) => f.startsWith('docs/rfcs/')));
  const cliRef = fs.readFileSync(new URL('../docs/reference/cli.md', import.meta.url), 'utf8');
  assert.equal(isGeneratedDoc(cliRef), true);
  assert.ok(DOCS_EXCLUDED_DIRS.includes('docs/rfcs/'));
});
