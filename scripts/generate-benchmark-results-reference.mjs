#!/usr/bin/env node
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const BENCHMARK_RESULTS_REFERENCE_PATH = 'docs/reference/benchmark-results.md';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Canonical committed runs surfaced by this reference. Kept as an explicit
// allow-list (rather than globbing benchmarks/results/**) so the doc renders the
// small-model headline runs and never drifts into rendering every historical or
// experimental sweep (e.g. beir/matrix/nomic-v2, beir/matrix/qwen3-q4preface).
// Add a new run here deliberately, then re-run `npm run docs:generate-benchmark-results`.
export const CANONICAL_ARTIFACTS = {
  mteb: [
    { label: 'nomic', path: 'benchmarks/results/mteb/nomic.json' },
    { label: 'qwen3', path: 'benchmarks/results/mteb/qwen3.json' },
  ],
  beirMatrix: [
    { label: 'nomic', path: 'benchmarks/results/beir/matrix/nomic/beir-matrix.json' },
    { label: 'qwen3', path: 'benchmarks/results/beir/matrix/qwen3/beir-matrix.json' },
  ],
  bright: [
    { label: 'nomic', path: 'benchmarks/results/bright/nomic/bright-report.json' },
    { label: 'qwen3', path: 'benchmarks/results/bright/qwen3/bright-report.json' },
  ],
};

export async function generateBenchmarkResultsReferenceMarkdown({ root = REPO_ROOT } = {}) {
  const [mteb, beirMatrix, bright] = await Promise.all([
    loadArtifacts(root, CANONICAL_ARTIFACTS.mteb),
    loadArtifacts(root, CANONICAL_ARTIFACTS.beirMatrix),
    loadArtifacts(root, CANONICAL_ARTIFACTS.bright),
  ]);

  const lines = [
    '# Benchmark Results Reference',
    '',
    '<!-- This file is generated by scripts/generate-benchmark-results-reference.mjs. Do not edit by hand. -->',
    '',
    'This reference lists retrieval-quality results from the benchmark runs',
    'committed under `benchmarks/results/`. It is generated from those result JSONs:',
    'run `npm run docs:generate-benchmark-results` after landing a new run, and',
    '`npm run docs:check-benchmark-results` fails in CI when this doc drifts from the',
    'artifacts. To surface a new run here, add its path to the `CANONICAL_ARTIFACTS`',
    'allow-list in `scripts/generate-benchmark-results-reference.mjs`, then regenerate.',
    '',
    'All numbers below are **local runs of two small embedding models',
    '(nomic-embed-text and Qwen3-Embedding-0.6B), not official leaderboard',
    'submissions.** Each section links the source artifact so the numbers stay',
    'traceable to a specific committed run and commit.',
    '',
    '### Reading these tables',
    '',
    'Each benchmark (MTEB, BEIR, BRIGHT) is a standard set of information-retrieval',
    'tasks — a corpus plus queries with relevance judgements (graded for MTEB and',
    'BEIR; binary for BRIGHT).',
    '',
    '- **nDCG@10** — normalized discounted cumulative gain over the top 10 results:',
    '  the primary metric for how well the top 10 are *ranked*.',
    '- **P@10 / R@10** — precision and recall over the same top 10.',
    '- **main_score** (MTEB) — the task-native primary metric MTEB reports.',
    '',
    'All scores run from 0 to 1, and higher is better.',
    '',
    'The **Datasets** column reads `n/m`: `n` of the `m` requested datasets were',
    'evaluated. Rows where `n < m` average a *different* subset of datasets, so they',
    'are not directly comparable to full `m/m` rows.',
    '',
    ...renderMtebSection(mteb),
    '',
    ...renderBeirMatrixSection(beirMatrix),
    '',
    ...renderBrightSection(bright),
  ];

  return `${lines.join('\n')}\n`;
}

function renderMtebSection(artifacts) {
  const lines = [
    '## MTEB',
    '',
    'Per-task `main_score` from the committed MTEB runs (schema `kb.mteb-result.v1`).',
    'The **Mean main_score** is the producer\'s mean over *every* task in the run, so',
    'the per-task table below always lists exactly the tasks that mean covers.',
    '',
  ];
  for (const { label, path: artifactPath, data } of artifacts) {
    lines.push(
      `### ${label} — ${escapeText(data.mteb_model_id ?? data.kb_model ?? '?')}`,
      '',
      ...renderProvenance([
        ['Source', sourceLink(artifactPath)],
        ['MTEB version', data.mteb_version ? code(data.mteb_version) : 'n/a'],
        ['Mean main_score (all tasks)', fmt(data.mean_main_score)],
      ]),
      '',
      '| Task | Split | main_score |',
      '|---|---|---:|',
    );
    for (const entry of data.tasks ?? []) {
      lines.push(`| ${code(entry.task)} | ${entry.split ? code(entry.split) : 'n/a'} | ${fmt(entry.main_score)} |`);
    }
    lines.push('');
  }
  lines.pop();
  return lines;
}

function renderBeirMatrixSection(artifacts) {
  const lines = [
    '## BEIR full-matrix',
    '',
    'Per-mode **multi-domain mean nDCG@10** — the mean across datasets, so no single',
    'dataset can dominate the headline (see RFC 020 §2/§6) — from each matrix run',
    '(schema `kb.beir-matrix.v1`). Each **Mode** is a retrieval strategy: `lexical`',
    '(BM25-style keyword search, which does not use the embedding model, so it is',
    'identical across models), `dense` (embedding similarity), `hybrid` (both fused),',
    'and `+rerank` / `+late` / `+contextual` variants layered on top.',
    '',
  ];
  for (const { label, path: artifactPath, data } of artifacts) {
    lines.push(
      `### ${label} — ${escapeText(data.env?.embedding_provider ?? '?')} / ${escapeText(data.env?.embedding_model ?? '?')}`,
      '',
      ...renderProvenance([
        ['Source', sourceLink(artifactPath)],
        ['Repo commit at run time', data.git_sha ? code(data.git_sha) : 'n/a'],
        ['Run timestamp (UTC)', data.generated_at ? code(data.generated_at) : 'n/a'],
        ['Datasets', (data.datasets ?? []).map(code).join(', ') || 'n/a'],
      ]),
      '',
      '| Mode | Datasets | Mean nDCG@10 | Mean P@10 | Mean R@10 |',
      '|---|---:|---:|---:|---:|',
    );
    for (const mode of data.perMode ?? []) {
      // A mode with zero datasets evaluated has no measured mean — never render a
      // producer-supplied 0 as if it were a score.
      const cell = (value) => (mode.datasetsEvaluated ? fmt(value) : 'n/a');
      lines.push(
        `| ${code(mode.mode)} | ${mode.datasetsEvaluated}/${mode.datasetsRequested} | ${cell(mode.multiDomainMeanNdcgAt10)} | ${cell(mode.multiDomainMeanPrecisionAt10)} | ${cell(mode.multiDomainMeanRecallAt10)} |`,
      );
    }
    lines.push('');
  }
  lines.pop();
  return lines;
}

function renderBrightSection(artifacts) {
  const lines = [
    '## BRIGHT',
    '',
    'nDCG@10 per task and mode from the committed local BRIGHT reproduction',
    '(schema `kb.bright-report.v1`). The committed run covers only the tasks and',
    'modes listed below — it is a partial run, not the full BRIGHT suite.',
    '',
  ];
  for (const { label, path: artifactPath, data } of artifacts) {
    lines.push(
      `### ${label} — ${escapeText(data.provider ?? '?')} / ${escapeText(data.model ?? '?')}`,
      '',
      ...renderProvenance([
        ['Source', sourceLink(artifactPath)],
        ['Repo commit at run time', data.git_sha ? code(data.git_sha) : 'n/a'],
        ['Run timestamp (UTC)', data.generated_at ? code(data.generated_at) : 'n/a'],
        ['Split', data.split ? code(data.split) : 'n/a'],
      ]),
      '',
      '| Task | Mode | nDCG@10 | P@10 | R@10 | Queries |',
      '|---|---|---:|---:|---:|---:|',
    );
    const failed = [];
    for (const point of data.points ?? []) {
      // A failed BRIGHT point carries an `error` key and zero metrics (see
      // benchmarks/bright/run.ts::failedPoint). Test for the key's presence, not
      // truthiness: `new Error()` yields error === "" — a real failure whose
      // zeros must never be rendered as measured scores. Surface it as `failed`
      // and list the error below.
      if (Object.prototype.hasOwnProperty.call(point, 'error')) {
        failed.push(point);
        lines.push(`| ${code(point.task)} | ${code(point.mode)} | failed | failed | failed | ${point.queriesEvaluated ?? 0} |`);
        continue;
      }
      lines.push(
        `| ${code(point.task)} | ${code(point.mode)} | ${fmt(point.ndcgAt10)} | ${fmt(point.precisionAt10)} | ${fmt(point.recallAt10)} | ${point.queriesEvaluated} |`,
      );
    }
    if (failed.length > 0) {
      lines.push('');
      for (const point of failed) {
        const message = point.error ? escapeText(point.error) : '(no error message)';
        lines.push(`> **Failed:** ${code(point.task)} / ${code(point.mode)} — ${message}`);
      }
    }
    if ((data.caveats ?? []).length > 0) {
      lines.push('', 'Caveats (from the run artifact):');
      for (const caveat of data.caveats) {
        lines.push(`- ${escapeText(caveat)}`);
      }
    }
    lines.push('');
  }
  lines.pop();
  return lines;
}

function renderProvenance(pairs) {
  return pairs.map(([key, value]) => `- **${key}:** ${value}`);
}

async function loadArtifacts(root, entries) {
  return Promise.all(
    entries.map(async (entry) => {
      const absolute = path.join(root, entry.path);
      let raw;
      try {
        raw = await fs.readFile(absolute, 'utf8');
      } catch (err) {
        if (err.code === 'ENOENT') {
          throw new Error(`Canonical benchmark artifact missing: ${entry.path}`);
        }
        throw err;
      }
      let data;
      try {
        data = JSON.parse(raw);
      } catch (err) {
        throw new Error(`Canonical benchmark artifact is not valid JSON: ${entry.path} (${err.message})`);
      }
      return { ...entry, data };
    }),
  );
}

export async function writeBenchmarkResultsReference({ root = REPO_ROOT } = {}) {
  const target = path.join(root, BENCHMARK_RESULTS_REFERENCE_PATH);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, await generateBenchmarkResultsReferenceMarkdown({ root }), 'utf8');
}

export async function checkBenchmarkResultsReference({ root = REPO_ROOT } = {}) {
  const expected = await generateBenchmarkResultsReferenceMarkdown({ root });
  const target = path.join(root, BENCHMARK_RESULTS_REFERENCE_PATH);
  let actual = null;
  try {
    actual = await fs.readFile(target, 'utf8');
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
  return { ok: actual === expected, exists: actual !== null };
}

function fmt(value) {
  if (typeof value !== 'number' || Number.isNaN(value)) return 'n/a';
  return value.toFixed(4);
}

function code(value) {
  // Escape `|` as well: these <code> spans land inside Markdown table cells, where
  // a bare pipe would silently start a new column.
  return `<code>${escapeHtml(String(value)).replaceAll('|', '\\|')}</code>`;
}

function escapeHtml(value) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function escapeText(value) {
  return String(value).replaceAll('|', '\\|');
}

function sourceLink(artifactPath) {
  return `[\`${artifactPath}\`](${path.posix.relative('docs/reference', artifactPath)})`;
}

async function main(argv) {
  if (argv.includes('--check')) {
    const { ok, exists } = await checkBenchmarkResultsReference();
    if (!ok) {
      process.stderr.write(
        [
          `${BENCHMARK_RESULTS_REFERENCE_PATH} is ${exists ? 'out of date' : 'missing'}.`,
          'Run `npm run docs:generate-benchmark-results` and commit the result.',
          '',
        ].join('\n'),
      );
      process.exitCode = 1;
    }
    return;
  }
  await writeBenchmarkResultsReference();
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch((err) => {
    process.stderr.write(`docs:generate-benchmark-results: ${err.message}\n`);
    process.exitCode = 1;
  });
}
